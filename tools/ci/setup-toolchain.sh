#!/bin/bash
# Install the build tools a clean CI machine lacks, at the versions the port is
# developed with: cmake, ninja, ccache, Emscripten, and Node when the machine
# has none recent enough.
#   tools/ci/setup-toolchain.sh [--prefix DIR] [--only node]
# Everything goes under the prefix (default: .toolchain in this checkout), so it
# needs no root and one CI cache entry holds all of it. The script writes
# <prefix>/env.sh, which tools/env.sh sources, and inside a workflow it also
# puts the tools on PATH for the steps that follow. A tool that is already
# installed at the right version is kept, so a prefix restored from the cache
# costs a second.
#   --only node   install nothing but Node: enough for the jobs that run the
#                 browser tests or the deployment and do not build.
# Needs bash, curl, git, tar, xz and python3 (Emscripten runs on python3), on
# x86-64 Linux.
set -euo pipefail

CMAKE_VERSION=4.5.0
CMAKE_SHA256=81f0d5b0960fb6adc8197030ffc827fba937640d51e73e39e0e9e40d88c66f6f
NINJA_VERSION=1.13.2
NINJA_SHA256=5749cbc4e668273514150a80e387a957f933c6ed3f5f11e03fb30955e2bbead6
CCACHE_VERSION=4.14.3
CCACHE_SHA256=d553fac006ed93a37342cee9228cf4e13dd66690fa1a8075c54c7bace9b72ae6
EMSCRIPTEN_VERSION=7.0.0
# The emsdk commit tagged 7.0.0; a commit cannot be moved the way a tag can.
EMSDK_COMMIT=1693ce7359fc9694f198694f902a2cc061239b86
# Node is only installed when the machine's own is older than NODE_MAJOR.
NODE_MAJOR=26
NODE_VERSION=26.13.1
NODE_SHA256=5c063e46bab0fbc1c17cc445d7ff129cbdcd0471be6ed83b6ab864f8143bc864

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
PREFIX=$ROOT/.toolchain
ONLY=
while [ $# -gt 0 ]; do
  case "$1" in
    --prefix) PREFIX=${2:?--prefix needs a directory}; shift 2 ;;
    --only) ONLY=${2:?--only needs a tool name}; shift 2 ;;
    *) echo "usage: setup-toolchain.sh [--prefix DIR] [--only node]" >&2; exit 2 ;;
  esac
done
[ -z "$ONLY" ] || [ "$ONLY" = node ] || { echo "--only knows node, not $ONLY" >&2; exit 2; }
[ "$(uname -sm)" = "Linux x86_64" ] || { echo "setup-toolchain.sh installs x86-64 Linux binaries; this is $(uname -sm)" >&2; exit 1; }
for tool in curl git tar xz python3 sha256sum; do
  command -v "$tool" >/dev/null || { echo "setup-toolchain.sh needs $tool" >&2; exit 1; }
done

MARK='# Generated by tools/ci/setup-toolchain.sh.'
# The developer toolchain described in CLAUDE.md lives in a .toolchain of its
# own making; never install over it.
if [ -f "$PREFIX/env.sh" ] && ! grep -qxF "$MARK" "$PREFIX/env.sh"; then
  echo "$PREFIX holds a toolchain this script did not install; pass --prefix to use another directory" >&2
  exit 1
fi
mkdir -p "$PREFIX/bin"
PREFIX=$(cd "$PREFIX" && pwd)
DOWNLOADS=$(mktemp -d "$PREFIX/download.XXXXXX")
trap 'rm -rf "$DOWNLOADS"' EXIT

note() { echo "setup-toolchain: $*"; }

# fetch <url> <sha256>: download into $DOWNLOADS and verify; the file's path
# is left in FETCHED. (Printing it instead would run fetch in a subshell, where
# a failed download does not stop the script.)
fetch() {
  FETCHED=$DOWNLOADS/${1##*/}
  curl -fsSL --retry 3 --retry-delay 5 -o "$FETCHED" "$1"
  echo "$2  $FETCHED" | sha256sum -c --quiet -
}

# unpack <archive> <directory>: extract a tarball whose single top-level folder
# becomes <directory>. It is moved into place only when complete, so a job
# killed half way never leaves something that looks installed.
unpack() {
  local staging
  staging=$(mktemp -d "$PREFIX/unpack.XXXXXX")
  tar -xf "$1" -C "$staging" --strip-components=1 "${@:3}"
  rm -rf "$2"
  mv "$staging" "$2"
  chmod 755 "$2"
}

link() { ln -sfn "$1" "$PREFIX/bin/$2"; }

install_cmake() {
  local dir=$PREFIX/cmake-$CMAKE_VERSION
  if [ ! -x "$dir/bin/cmake" ]; then
    note "installing cmake $CMAKE_VERSION"
    # The manuals are a third of the archive and nothing reads them.
    fetch "https://github.com/Kitware/CMake/releases/download/v$CMAKE_VERSION/cmake-$CMAKE_VERSION-linux-x86_64.tar.gz" "$CMAKE_SHA256"
    unpack "$FETCHED" "$dir" --exclude="cmake-$CMAKE_VERSION-linux-x86_64/doc" --exclude="cmake-$CMAKE_VERSION-linux-x86_64/man"
  fi
  link "$dir/bin/cmake" cmake
  link "$dir/bin/ctest" ctest
}

install_ninja() {
  local dir=$PREFIX/ninja-$NINJA_VERSION
  if [ ! -x "$dir/ninja" ]; then
    note "installing ninja $NINJA_VERSION"
    fetch "https://github.com/ninja-build/ninja/releases/download/v$NINJA_VERSION/ninja-linux.zip" "$NINJA_SHA256"
    rm -rf "$dir" "$dir.partial"
    # python3 is required anyway; unzip is not on every image.
    python3 -I -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extract("ninja", sys.argv[2])' "$FETCHED" "$dir.partial"
    chmod 755 "$dir.partial/ninja"
    mv "$dir.partial" "$dir"
  fi
  link "$dir/ninja" ninja
}

install_ccache() {
  local dir=$PREFIX/ccache-$CCACHE_VERSION
  if [ ! -x "$dir/ccache" ]; then
    note "installing ccache $CCACHE_VERSION"
    # The static build runs whatever C library the image has.
    fetch "https://github.com/ccache/ccache/releases/download/v$CCACHE_VERSION/ccache-$CCACHE_VERSION-linux-x86_64-musl-static.tar.xz" "$CCACHE_SHA256"
    unpack "$FETCHED" "$dir"
  fi
  link "$dir/ccache" ccache
}

install_node() {
  local dir=$PREFIX/node-$NODE_VERSION have
  if [ ! -x "$dir/bin/node" ]; then
    # Look past our own bin directory: a link left there by an earlier run
    # must not count as the machine's Node.
    have=$(type -ap node 2>/dev/null | grep -vxF "$PREFIX/bin/node" | head -1 || true)
    if [ -n "$have" ] && [ "$("$have" -p 'process.versions.node.split(".")[0]')" -ge "$NODE_MAJOR" ]; then
      note "keeping the machine's Node $("$have" --version) ($have)"
      rm -f "$PREFIX/bin/node" "$PREFIX/bin/npm" "$PREFIX/bin/npx"
      return
    fi
    note "installing Node $NODE_VERSION"
    fetch "https://nodejs.org/dist/v$NODE_VERSION/node-v$NODE_VERSION-linux-x64.tar.xz" "$NODE_SHA256"
    unpack "$FETCHED" "$dir"
  fi
  link "$dir/bin/node" node
  link "$dir/bin/npm" npm
  link "$dir/bin/npx" npx
}

install_emscripten() {
  local dir=$PREFIX/emsdk
  if [ "$(cat "$dir/.arcade-installed" 2>/dev/null)" = "$EMSDK_COMMIT $EMSCRIPTEN_VERSION" ]; then
    return
  fi
  note "installing Emscripten $EMSCRIPTEN_VERSION"
  rm -rf "$dir"
  git init -q "$dir"
  git -C "$dir" fetch -q --depth 1 https://github.com/emscripten-core/emsdk "$EMSDK_COMMIT"
  git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD
  "$dir/emsdk" install "$EMSCRIPTEN_VERSION"
  "$dir/emsdk" activate "$EMSCRIPTEN_VERSION"
  # The downloaded archives are not needed again and would double the cache entry.
  rm -rf "$dir/downloads" "$dir/.git"
  echo "$EMSDK_COMMIT $EMSCRIPTEN_VERSION" > "$dir/.arcade-installed"
}

STARTED=$SECONDS
install_node
if [ -z "$ONLY" ]; then
  install_cmake
  install_ninja
  install_ccache
  install_emscripten
fi

# tools/env.sh sources this file, as it does the developer toolchain's.
cat > "$PREFIX/env.sh" <<EOF
$MARK
TC=\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)
export EKA2L1_TOOLCHAIN=\$TC
case ":\$PATH:" in *":\$TC/bin:"*) ;; *) export PATH=\$TC/bin:\$PATH ;; esac
if [ -f "\$TC/emsdk/emsdk_env.sh" ]; then
  export EMSDK_QUIET=1
  . "\$TC/emsdk/emsdk_env.sh" >/dev/null 2>&1
fi
# ccache would identify the compiler by emcc's timestamp, which changes every
# time the toolchain is installed again. Its version says what matters, and
# paths below the checkout are hashed relative to it, so a cache made in one
# workspace is still good in another. A full build stores about 110 MB.
export CCACHE_COMPILERCHECK=string:emscripten-$EMSCRIPTEN_VERSION
export CCACHE_BASEDIR=\${ARCADE_ROOT:-\$PWD}
export CCACHE_NOHASHDIR=1
export CCACHE_MAXSIZE=400M
EOF

# Inside a workflow, later steps get the tools without sourcing anything.
if [ -n "${GITHUB_PATH:-}" ]; then
  echo "$PREFIX/bin" >> "$GITHUB_PATH"
fi

export PATH=$PREFIX/bin:$PATH
note "node $(node --version)"
if [ -z "$ONLY" ]; then
  # shellcheck disable=SC1091
  . "$PREFIX/env.sh"
  note "$(cmake --version | head -1)"
  note "ninja $(ninja --version)"
  note "$(ccache --version | head -1)"
  note "$(emcc --version | head -1)"
fi
note "ready in $((SECONDS - STARTED)) s under $PREFIX"
